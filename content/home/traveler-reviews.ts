/**
 * Only approved feedback with website-use authorization may reach public UI.
 * Future Supabase-backed submissions should be mapped through this same shape.
 */
export const travelerReviews: TravelerReview[] = submittedTravelerReviews.map((review) => ({
  ...review,
  reviewStatus: "approved",
  authorizationStatus: "authorized",
  sourceType: "guest-submitted",
  publishedAt: "2026-10-04",
}));

export function getPublicTravelerReviews(reviews = travelerReviews) {
  return reviews.filter(
    (review) => review.reviewStatus === "approved" && review.authorizationStatus === "authorized",
  );
}

export function getInterleavedTravelerReviews(reviews = travelerReviews) {
  const groups = new Map<TravelerReviewLanguage, TravelerReview[]>();

  for (const review of getPublicTravelerReviews(reviews)) {
    const group = groups.get(review.language) ?? [];
    group.push(review);
    groups.set(review.language, group);
  }

  const queues = [...groups.values()];
  const interleaved: TravelerReview[] = [];
  let index = 0;

  while (queues.some((queue) => index < queue.length)) {
    for (const queue of queues) {
      const review = queue[index];
      if (review) interleaved.push(review);
    }
    index += 1;
  }

  return interleaved;
}
