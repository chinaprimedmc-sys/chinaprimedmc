import { readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = process.cwd();
const sourceRoot = "/Users/Admin/Desktop/美食+文化";
const outputDir = path.join(root, "public/home/story-optimized");
const manifestPath = path.join(root, "content/home/story-media.generated.ts");

const sharpPackage = (await readdir(path.join(root, "node_modules/.pnpm"))).find((entry) =>
  entry.startsWith("sharp@"),
);

if (!sharpPackage) throw new Error("Sharp is not installed.");

const { default: sharp } = await import(
  pathToFileURL(
    path.join(root, "node_modules/.pnpm", sharpPackage, "node_modules/sharp/lib/index.js"),
  ).href
);

const collections = [
  { id: "food", sourceDir: path.join(sourceRoot, "美食") },
  { id: "culture", sourceDir: path.join(sourceRoot, "文化体验") },
];

await Promise.all(
  collections.flatMap(({ id }) =>
    ["avif", "webp"].map((extension) => rmMatching(`${id}-*.${extension}`)),
  ),
);

const generated = {};

for (const collection of collections) {
  const files = (await readdir(collection.sourceDir, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && /\.(jpe?g|png|webp|heic)$/i.test(entry.name))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b, "zh-CN", { numeric: true }));

  generated[collection.id] = [];

  for (const [index, filename] of files.entries()) {
    const number = String(index + 1).padStart(3, "0");
    const basename = `${collection.id}-${number}`;
    const input = path.join(collection.sourceDir, filename);
    const fullPipeline = sharp(input)
      .rotate()
      .resize(640, 853, { fit: "cover", position: "attention" });
    const smallPipeline = sharp(input)
      .rotate()
      .resize(384, 512, { fit: "cover", position: "attention" });
    const fullscreenPipeline = sharp(input)
      .rotate()
      .resize(1280, 1707, { fit: "cover", position: "attention", withoutEnlargement: true });

    await Promise.all([
      fullPipeline
        .clone()
        .avif({ quality: 48, effort: 5, chromaSubsampling: "4:2:0" })
        .toFile(path.join(outputDir, `${basename}.avif`)),
      fullPipeline
        .clone()
        .webp({ quality: 70, effort: 5, smartSubsample: true })
        .toFile(path.join(outputDir, `${basename}.webp`)),
      smallPipeline
        .clone()
        .avif({ quality: 45, effort: 5, chromaSubsampling: "4:2:0" })
        .toFile(path.join(outputDir, `${basename}-384.avif`)),
      smallPipeline
        .clone()
        .webp({ quality: 66, effort: 5, smartSubsample: true })
        .toFile(path.join(outputDir, `${basename}-384.webp`)),
      fullscreenPipeline
        .clone()
        .avif({ quality: 52, effort: 5, chromaSubsampling: "4:2:0" })
        .toFile(path.join(outputDir, `${basename}-1280.avif`)),
      fullscreenPipeline
        .clone()
        .webp({ quality: 76, effort: 5, smartSubsample: true })
        .toFile(path.join(outputDir, `${basename}-1280.webp`)),
    ]);

    generated[collection.id].push({
      src: `/home/story-optimized/${basename}.avif`,
      alt: createAlt(collection.id, filename),
      width: 640,
      height: 853,
      caption: createCaption(collection.id, filename),
    });
  }
}

const manifest = `// Generated by scripts/build-home-story-media.mjs.\n\nexport type GeneratedStoryImage = {\n  src: string;\n  alt: string;\n  width: number;\n  height: number;\n  caption: string;\n};\n\nexport const foodStoryImages: GeneratedStoryImage[] = ${JSON.stringify(generated.food, null, 2)};\n\nexport const cultureStoryImages: GeneratedStoryImage[] = ${JSON.stringify(generated.culture, null, 2)};\n`;

await writeFile(manifestPath, manifest);

console.log(
  `Generated ${generated.food.length} food and ${generated.culture.length} culture photographs.`,
);

async function rmMatching(pattern) {
  const escaped = pattern.replace(/[.+^${}()|[\]\\]/g, "\\$&").replaceAll("*", ".*");
  const matcher = new RegExp(`^${escaped}$`);
  const files = await readdir(outputDir);
  await Promise.all(
    files.filter((file) => matcher.test(file)).map((file) => rm(path.join(outputDir, file))),
  );
}

function createAlt(type, filename) {
  if (type === "culture") {
    if (filename.includes("油纸伞")) return "International visitors making a traditional Chinese oil-paper umbrella";
    if (filename.includes("竹编")) return "International visitors learning traditional Chinese bamboo weaving";
    if (filename.includes("中国结")) return "International visitors learning to make a traditional Chinese knot";
    if (filename.includes("川剧") || filename.includes("非遗表演")) return "A live Sichuan opera and intangible cultural heritage performance in Chengdu";
    if (filename.includes("茶")) return "International visitors experiencing Chinese tea culture";
    if (filename.includes("簪花")) return "International visitors wearing traditional floral headdresses in Quanzhou";
    if (filename.includes("蓝染")) return "International visitors trying traditional Chinese indigo dyeing";
    if (filename.includes("宫宴") || filename.includes("盛世")) return "A theatrical Chinese palace banquet cultural experience";
    return "International visitors taking part in a hands-on Chinese cultural experience";
  }

  if (filename.includes("火锅") || filename.includes("铜锅涮")) return "Travelers sharing a local Chinese hotpot meal";
  if (filename.includes("早茶")) return "A table filled with Cantonese dim sum and morning tea";
  if (filename.includes("烤鸭")) return "An international traveler enjoying Beijing roast duck";
  if (filename.includes("面")) return "International visitors enjoying local Chinese noodles";
  if (filename.includes("烧烤") || filename.includes("烤串")) return "Freshly grilled skewers at a local Chinese restaurant";
  if (filename.includes("糖人")) return "A traditional Chinese sugar figurine being made by hand";
  if (filename.includes("筷子")) return "International visitors learning to eat local food with chopsticks";
  return "Travelers enjoying local dishes together in China";
}

function createCaption(type, filename) {
  const location = [
    ["北京", "Beijing"],
    ["西安", "Xi'an"],
    ["成都", "Chengdu"],
    ["重庆", "Chongqing"],
    ["广州", "Guangzhou"],
    ["广东", "Guangdong"],
    ["深圳", "Shenzhen"],
    ["新疆", "Xinjiang"],
    ["伊犁", "Yili"],
    ["贵州", "Guizhou"],
    ["贵阳", "Guiyang"],
    ["昆明", "Kunming"],
    ["桂林", "Guilin"],
    ["泉州", "Quanzhou"],
  ].find(([keyword]) => filename.includes(keyword))?.[1];

  return type === "culture"
    ? `${location ?? "China"} · Tradition experienced firsthand`
    : `${location ?? "China"} · Local flavors shared around the table`;
}
